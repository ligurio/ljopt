#!/usr/bin/env lua

local function read(path)
    local fh = assert(io.open(path, 'r'))
    local s = fh:read('*a')
    fh:close()
    return s
end

local function macro_body(src, name)
    local at = src:find('#define ' .. name .. '%(_%)')
    if not at then error(name .. ' not found') end
    local body = {}
    for line in src:sub(at):gmatch('[^\n]*\n') do
        body[#body + 1] = line
        if not line:match('\\%s*$') then break end
    end
    return table.concat(body):gsub('/%*.-%*/', ' ')
end

local function parse_ops(src)
    local ops = {}
    for name, mode, op1, op2 in macro_body(src, 'IRDEF'):gmatch(
            '_%(%s*([A-Z][A-Z0-9_]*)%s*,%s*([A-Z]+)%s*,%s*([a-z_]+)%s*,%s*([a-z_]+)%s*%)') do
        ops[#ops + 1] = { name = name, mode = mode, op1 = op1, op2 = op2 }
    end
    return ops
end

local function parse_names(src, macro)
    local names = {}
    for name in macro_body(src, macro):gmatch('_%(%s*([A-Z][A-Z0-9_]*)') do
        names[#names + 1] = name
    end
    return names
end

local function parse_types(src)
    local types = {}
    for name in macro_body(src, 'IRTDEF'):gmatch('_%(%s*([A-Z][A-Z0-9_]*)%s*,') do
        types[#types + 1] = name
    end
    return types
end

local function quoted_list(names, indent)
    local out, line = {}, indent
    for _, name in ipairs(names) do
        local item = string.format('%q, ', name)
        if #line + #item > 78 then
            out[#out + 1] = line:gsub('%s+$', '')
            line = indent
        end
        line = line .. item
    end
    out[#out + 1] = line:gsub(',%s*$', '')
    return table.concat(out, '\n')
end

local header = assert(arg[1], 'usage: gen_opcodes.lua <lj_ir.h> [tag]')
local tag = arg[2] or 'unknown'
local src = read(header)

local ops = parse_ops(src)
local out = {}
out[#out + 1] = '-- Generated by scripts/gen_opcodes.lua. Do not edit.'
out[#out + 1] = string.format('local LUAJIT_TAG = %q', tag)
out[#out + 1] = ''
out[#out + 1] = 'local ops = {'
for i, op in ipairs(ops) do
    out[#out + 1] = string.format(
        '    { name = %q, num = %d, mode = %q, op1 = %q, op2 = %q },',
        op.name, i - 1, op.mode, op.op1, op.op2)
end
out[#out + 1] = '}'
out[#out + 1] = ''
out[#out + 1] = 'local types = {'
out[#out + 1] = quoted_list(parse_types(src), '    ')
out[#out + 1] = '}'
out[#out + 1] = ''
out[#out + 1] = 'local fields = {'
out[#out + 1] = quoted_list(parse_names(src, 'IRFLDEF'), '    ')
out[#out + 1] = '}'
out[#out + 1] = ''
out[#out + 1] = 'local fpmath = {'
out[#out + 1] = quoted_list(parse_names(src, 'IRFPMDEF'), '    ')
out[#out + 1] = '}'
out[#out + 1] = ''
out[#out + 1] = [[
local by_name = {}
for _, op in ipairs(ops) do by_name[op.name] = op end

return {
    luajit_tag = LUAJIT_TAG,
    ops = ops,
    by_name = by_name,
    types = types,
    fields = fields,
    fpmath = fpmath,
}]]

io.write(table.concat(out, '\n'), '\n')
